# ---------------- 指标正确性（显式 predictions） ----------------

def _eval(preds, questions):
    return eval_metrics.evaluate(preds, questions)


def test_metrics_retrieval_and_citation_correctness():
    questions = [
        _q(id="q1", gold_pages=[{"document_id": "docA", "physical_page": 1,
                                 "printed_page": 1, "evidence": "x"}]),
    ]
    preds = [{
        "query_id": "q1",
        "retrieved": [{"document_id": "docA", "physical_page": 1},
                      {"document_id": "docA", "physical_page": 2},
                      {"document_id": "docB", "physical_page": 1}],
        "citations": [{"document_id": "docA", "physical_page": 1}],
        "answer": "composite measure", "no_answer": False,
    }]
    r = _eval(preds, questions)
    m = r["metrics"]
    assert m["recall@1"] == 1.0 and m["recall@3"] == 1.0
    assert m["precision@1"] == 1.0 and m["precision@3"] == pytest.approx(1 / 3)
    assert m["mrr"] == 1.0
    assert m["citation_page_precision"] == 1.0
    assert m["citation_recall"] == 1.0


def test_cross_document_same_page_not_confused():
    # 跨文档同页号：引用 (docB, p1) 不算命中 gold (docA, p1)
    questions = [_q(id="q1")]
    preds = [{
        "query_id": "q1",
        "retrieved": [{"document_id": "docB", "physical_page": 1}],
        "citations": [{"document_id": "docB", "physical_page": 1}],
        "answer": "", "no_answer": True,
    }]
    m = _eval(preds, questions)["metrics"]
    assert m["citation_page_precision"] == 0.0
    assert m["citation_recall"] == 0.0
    assert m["recall@1"] == 0.0


def test_hard_negative_metrics():
    questions = [
        _q(id="q1", gold_pages=[{"document_id": "docA", "physical_page": 1,
                                 "printed_page": 1, "evidence": "x"}]),
        _q(id="q2", gold_pages=[{"document_id": "docA", "physical_page": 2,
                                 "printed_page": 2, "evidence": "y"}]),
    ]
    # q1 检索到同文档错页 (docA,p2) 与跨文档页 (docB,p1)
    preds = [{
        "query_id": "q1",
        "retrieved": [{"document_id": "docA", "physical_page": 2},
                      {"document_id": "docB", "physical_page": 1}],
        "citations": [{"document_id": "docA", "physical_page": 2}],
        "answer": "", "no_answer": True,
    }]
    row = eval_metrics.per_query_metrics(preds[0], questions[0], questions, ks=(1, 2, 5))
    assert row["hard_negative_recall@2"] == 1.0  # 全部 hard negative 都被误召回
    assert row["hard_negative_citations"] == 1   # 误引用了 hard negative


def test_answer_scoring_types():
    numeric = _q(id="n1", answer_type="numeric", numeric={"value": 300.0,
                 "tolerance": {"type": "relative", "value": 0.15}})
    # 数值容差内命中
    assert eval_metrics.score_answer(
        {"query_id": "n1", "answer": "about 290 flights"}, numeric)["correct"]
    assert not eval_metrics.score_answer(
        {"query_id": "n1", "answer": "about 500 flights"}, numeric)["correct"]
    # 绝对容差
    abs_q = _q(id="a1", answer_type="numeric",
               numeric={"value": 10.0, "tolerance": {"type": "absolute", "value": 2.0}})
    assert eval_metrics.score_answer({"query_id": "a1", "answer": "9"}, abs_q)["correct"]
    # exact EM
    assert eval_metrics.score_answer(
        {"query_id": "t1", "answer": "Composite Measure"}, _q())["correct"]
    assert not eval_metrics.score_answer(
        {"query_id": "t1", "answer": "probability"}, _q())["correct"]
    # set F1：全覆盖才算对
    set_q = _q(id="s1", answer_type="set", gold_answers=["a", "b", "c"])
    assert eval_metrics.score_answer(
        {"query_id": "s1", "answer": "a b c"}, set_q)["correct"]
    assert not eval_metrics.score_answer(
        {"query_id": "s1", "answer": "a b"}, set_q)["correct"]
    # rubric checklist
    rub_q = _q(id="r1", answer_type="rubric", gold_answers=[],
               rubric={"points": ["probability of occurring", "magnitude of consequences"],
                       "min_points": 2})
    assert eval_metrics.score_answer(
        {"query_id": "r1", "answer": "probability of occurring and the magnitude of consequences"},
        rub_q)["correct"]
    # 弃答：no_answer + 空答案 + 无引用才得分
    u_q = _q(id="u1", answer_type="unanswerable", unanswerable=True,
             gold_pages=[], gold_answers=[])
    assert eval_metrics.score_answer(
        {"query_id": "u1", "answer": "", "no_answer": True, "citations": []}, u_q)["correct"]
    assert not eval_metrics.score_answer(
        {"query_id": "u1", "answer": "some text", "no_answer": True, "citations": []}, u_q)["correct"]
    assert not eval_metrics.score_answer(
        {"query_id": "u1", "answer": "", "no_answer": True,
         "citations": [{"document_id": "docA", "physical_page": 1}]}, u_q)["correct"]


def test_ci_bootstrap_deterministic():
    vals = [1.0, 0.5, 0.0, 1.0, 0.5, 0.0] * 4
    assert eval_metrics.bootstrap_ci(vals, seed=7) == eval_metrics.bootstrap_ci(vals, seed=7)
    lo, hi = eval_metrics.wilson_ci(8, 10)
    assert lo < 0.8 < hi


def test_slices_cover_dimensions():
    questions = [
        _q(id="e1", gold_pages=[GOLD_PAGE]),
        _q(id="e2", language="zh", answer_type="set", gold_answers=["a"],
           gold_pages=[GOLD_PAGE], tags=["zh-tag"]),
    ]
    preds = [{"query_id": q["id"], "retrieved": [], "citations": [],
              "answer": "x", "no_answer": False} for q in questions]
    sl = _eval(preds, questions)["slices"]
    assert "en" in sl["language"] and "zh" in sl["language"]
    assert set(sl["answer_type"]) == {"exact", "set"}
    assert "zh-tag" in sl["tag"]
    assert "docA" in sl["document"]


