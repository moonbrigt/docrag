# 小合成语料（两文档、跨文档同页号，用于指标正确性验证）
CORPUS = [
    {"document_id": "docA", "physical_page": 1,
     "text": "The AI RMF defines risk as the composite measure of probability and consequences."},
    {"document_id": "docA", "physical_page": 2,
     "text": "NIST identifies three bias categories: systemic, computational and statistical, and human-cognitive."},
    {"document_id": "docB", "physical_page": 1,
     "text": "Confabulation refers to erroneous content generated by GAI systems in response to prompts."},
]

GOLD_PAGE = {"document_id": "docA", "physical_page": 1, "printed_page": 1,
             "evidence": "risk as the composite measure of probability and consequences"}


def _q(**overrides) -> dict:
    q = {
        "id": "t1", "query": "how is risk defined?", "answer_type": "exact",
        "gold_answers": ["composite measure"], "gold_pages": [GOLD_PAGE],
        "language": "en", "tags": ["t"], "split": "test", "unanswerable": False,
    }
    q.update(overrides)
    return q


# ---------------- manifest / 下载 / gold 校验（fail-closed） ----------------

def test_manifest_validation_fails_on_missing_field():
    manifest = public_dataset.load_manifest()
    bad = dict(manifest)
    del bad["sources"]
    with pytest.raises(ValueError, match="sources"):
        public_dataset.validate_manifest(bad)
    bad2 = dict(manifest)
    bad2["sources"] = [dict(manifest["sources"][0], sha256="abc")]
    with pytest.raises(ValueError, match="sha256"):
        public_dataset.validate_manifest(bad2)


def test_download_bad_hash_fail_closed(tmp_path):
    src = tmp_path / "src.bin"
    src.write_bytes(b"hello world")
    uri = src.as_uri()
    dest = tmp_path / "out.bin"
    with pytest.raises(ValueError, match="SHA-256"):
        public_dataset.download_file(uri, dest, "0" * 64, len(b"hello world"))
    # 期望尺寸不符也失败
    with pytest.raises(ValueError, match="尺寸"):
        public_dataset.download_file(uri, dest, "0" * 64, 9999)
    assert not dest.exists()  # fail-closed：不留半成品
    assert not (tmp_path / "out.bin.part").exists()


